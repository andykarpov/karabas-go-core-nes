#!/usr/bin/env python3
"""nes_palette.h for sim_nes.cpp: the 64 colours of the NES palette from rtl/vga/vga.vhd (the board output).

Usage: gen_palette.py <vga.vhd> <nes_palette.h>
"""
import re
import sys

src = open(sys.argv[1]).read()
pal = {int(i, 2): int(c, 16) for i, c in re.findall(r'when "([01]{6})" => rgb <= X"([0-9A-Fa-f]{6})"', src)}
if sorted(pal) != list(range(64)):
    sys.exit("%s: %d palette entries, 64 expected" % (sys.argv[1], len(pal)))
with open(sys.argv[2], "w") as f:
    f.write("// generated by gen_palette.py from rtl/vga/vga.vhd\n#include <cstdint>\nstatic const uint32_t nes_palette[64] = {\n")
    for i in range(0, 64, 8):
        f.write("\t" + ", ".join("0x%06X" % pal[j] for j in range(i, i + 8)) + ",\n")
    f.write("};\n")
